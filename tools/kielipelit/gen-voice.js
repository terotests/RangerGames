// Writes the English and Spanish voice clip lists from games/kielipelit/lib/words.ts:
//   voice/<lang>/common.json      words, colours, praise (shared by every game)
//   voice/<lang>/kielipelit.json  the sentences of Kielipelit (ids kp_…)
// node tools/kielipelit/gen-voice.js
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..", "..");
const names = [];
const src = fs.readFileSync(path.join(root, "games/kielipelit/lib/words.ts"), "utf8")
  .replace(/export const (\w+)(?::[^=]+)? =/g, (_m, n) => { names.push(n); return "const " + n + " ="; })
  .replace(/export function (\w+)/g, (_m, n) => { names.push(n); return "function " + n; });
const D = {};
new Function("D", src + "\n" + names.map((n) => "D." + n + " = " + n + ";").join("\n"))(D);

for (const lang of ["en", "es"]) {
  const all = D.clipTexts(lang), common = all.common, game = all.game;
  const write = (file, comment, clips) => {
    const out = path.join(root, "voice", lang, file);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, JSON.stringify({ _comment: comment, lang, clips }, null, 1) + "\n");
    console.log(out, Object.keys(clips).length, "clips");
  };
  write("common.json", "GENERATED by tools/kielipelit/gen-voice.js from games/kielipelit/lib/words.ts. Words (id = English word), colours and praise for every game. Add a word there, not here.", common);
  write("kielipelit.json", "GENERATED by tools/kielipelit/gen-voice.js from games/kielipelit/lib/words.ts: the sentences of Kielipelit.", game);
}
