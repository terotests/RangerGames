"""Tampere's tram timetable for the Kotiin navigator, from Nysse's GTFS feed
(the tram routes; data (c) Tampereen joukkoliikenne Nysse, CC BY 4.0):

  python3 tools/navi/tram.py <gtfs dir or zip> -> games/navi/tram.js

Each trip pattern (line, direction, stop sequence) keeps its stops, the
median seconds from the first stop to each stop, and the minute each trip
leaves the first stop for four kinds of day: 0 Monday-Thursday, 1 Friday,
2 Saturday, 3 Sunday (the regular services of the feed's longest period)."""
import csv, io, json, os, sys, zipfile
from collections import defaultdict, Counter
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ttd

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")


def reader(src):
    if src.endswith(".zip"):
        z = zipfile.ZipFile(src)
        return lambda n: csv.DictReader(io.TextIOWrapper(z.open(n), encoding="utf-8-sig"))
    return lambda n: csv.DictReader(open(os.path.join(src, n), encoding="utf-8-sig"))


def secs(t):
    h, m, s = t.split(":")
    return int(h) * 3600 + int(m) * 60 + int(s)


def main():
    rd = reader(sys.argv[1])
    # the regular services: per kind of day, the one valid longest
    best = {}
    for c in rd("calendar.txt"):
        days = [c[d] == "1" for d in ("monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday")]
        if days[0] and days[3]: kind = 0
        elif days[4] and not days[0]: kind = 1
        elif days[5] and not days[4]: kind = 2
        elif days[6] and not days[5]: kind = 3
        else: continue
        span = int(c["end_date"]) - int(c["start_date"])
        if kind not in best or span > best[kind][1]:
            best[kind] = (c["service_id"], span)
    service_kind = {v[0]: k for k, v in best.items()}
    print("services:", {k: v[0] for k, v in sorted(best.items())})
    routes = {r["route_id"]: r["route_short_name"] for r in rd("routes.txt")}
    trips = {}
    for t in rd("trips.txt"):
        if t["service_id"] in service_kind:
            trips[t["trip_id"]] = (routes[t["route_id"]], t["trip_headsign"], int(t["direction_id"]), service_kind[t["service_id"]])
    stops = {s["stop_id"]: s for s in rd("stops.txt")}
    times = defaultdict(list)
    for st in rd("stop_times.txt"):
        if st["trip_id"] in trips:
            times[st["trip_id"]].append((int(st["stop_sequence"]), st["stop_id"], secs(st["departure_time"])))
    pats = {}
    for tid, rows in times.items():
        rows.sort()
        seq = tuple(r[1] for r in rows)
        line, head, di, kind = trips[tid]
        key = (line, di, head, seq)
        p = pats.setdefault(key, {"offs": [], "dep": [[], [], [], []]})
        t0 = rows[0][2]
        p["offs"].append([r[2] - t0 for r in rows])
        p["dep"][kind].append(t0 // 60)
    used = []
    index = {}
    def stop_index(sid):
        if sid not in index:
            s = stops[sid]
            name = s["stop_name"]
            base, plat = (name[:-2], name[-1]) if len(name) > 2 and name[-2] == " " and name[-1].isalpha() else (name, "")
            x, z = ttd.to_xz(float(s["stop_lat"]), float(s["stop_lon"]))
            index[sid] = len(used)
            used.append({"n": base, "p": plat, "x": round(x, 1), "z": round(z, 1)})
        return index[sid]
    out = []
    for (line, di, head, seq), p in sorted(pats.items(), key=lambda kv: (kv[0][0], kv[0][1], -len(kv[1]["offs"]))):
        n = len(p["offs"])
        if n < 3:
            continue  # odd one-off trips (to the depot)
        offs = [sorted(o[k] for o in p["offs"])[n // 2] for k in range(len(seq))]
        out.append({"line": line, "head": head, "stops": [stop_index(s) for s in seq], "off": offs,
                    "dep": [sorted(d) for d in p["dep"]]})
        print(f"line {line} -> {head}: {len(seq)} stops, {n} trips, {offs[-1] // 60} min")
    with open(os.path.join(ROOT, "games", "navi", "tram.js"), "w") as fh:
        fh.write("// GENERATED by tools/navi/tram.py from Nysse's GTFS feed (CC BY 4.0): the tram timetable.\n")
        fh.write("export const TRAM = " + json.dumps({"stops": used, "pats": out}, ensure_ascii=False, separators=(",", ":")) + ";\n")


main()
