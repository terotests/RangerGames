"""Builds the offline map of the Kotiin navigator (games/navi) from Tampere
Taxi Driver's city map (github.com/terotests/TampereTaxiDriver,
data/tampere-full.ttd.gz):

  games/navi/tiles/d/<i>_<j>.webp   map tiles, 2 m a pixel, 512 px = 1024 m
  games/navi/tiles/o/<i>_<j>.webp   overview tiles, 8 m a pixel
  games/navi/net.js                 the walking network (graph) as one string

Usage: python3 tools/navi/build.py <tampere-full.ttd.gz> [--no-tiles]

No addresses are in any of this: the homes are set on the phone.
Map data (c) OpenStreetMap contributors (ODbL), Tampereen kaupunki /
Maanmittauslaitos (CC BY 4.0)."""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ttd, graph, render

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
OUT = os.path.join(ROOT, "games", "navi")
BOX = (-10400, -3200, 11600, 8200)  # x0 z0 x1 z1, metres (Lielahti - Hervanta, Pispala - Messukylä)
TILE = 512
LEVELS = {"d": 2.0, "o": 8.0}


def b36(n):
    n = int(n)
    if n == 0: return "0"
    neg = n < 0; n = abs(n); s = ""
    while n:
        s = "0123456789abcdefghijklmnopqrstuvwxyz"[n % 36] + s; n //= 36
    return ("-" if neg else "") + s


def tiles(d):
    r = render.Renderer(d)
    have = {}
    for lv, mpp in LEVELS.items():
        span = TILE * mpp
        os.makedirs(os.path.join(OUT, "tiles", lv), exist_ok=True)
        nx = int(-(-(BOX[2] - BOX[0]) // span)); nz = int(-(-(BOX[3] - BOX[1]) // span))
        have[lv] = []
        for j in range(nz):
            for i in range(nx):
                img = r.render(BOX[0] + i * span, BOX[1] + j * span, mpp, TILE, TILE)
                ex = img.getextrema()
                if all(lo == hi for lo, hi in ex):
                    continue  # one colour (empty): the game paints the background
                img.save(os.path.join(OUT, "tiles", lv, f"{i}_{j}.webp"), quality=80, method=6)
                have[lv].append(f"{i}_{j}")
        print(f"tiles {lv}: {len(have[lv])} of {nx * nz}")
    return have


def net(d):
    nodes, edges = graph.build(d, BOX)
    f, size = graph.components(nodes, edges)
    main = max(size, key=size.get)
    keep = [i for i in range(len(nodes)) if f(i) == main]
    # nodes in a spatial order (rows of 200 m) so the deltas stay small
    keep.sort(key=lambda i: (int(nodes[i][1] // 200), nodes[i][0]))
    new = {o: n for n, o in enumerate(keep)}
    dm = lambda v: int(round(v * 10))
    out = [len(keep)]
    px = pz = 0
    for o in keep:
        x, z = dm(nodes[o][0]), dm(nodes[o][1])
        out += [x - px, z - pz]; px, pz = x, z
    es = [e for e in edges if e[0] in new and e[1] in new]
    out.append(len(es))
    # edge: a b cost-per-metre*20 npts (dx dz from the previous point)...
    for a, b, L, cost, pts, name in es:
        A, B = new[a], new[b]
        out += [A, B - A, int(round(cost / L * 20)), len(pts)]
        x, z = dm(nodes[a][0]), dm(nodes[a][1])
        for p in pts:
            X, Z = dm(p[0]), dm(p[1])
            out += [X - x, Z - z]; x, z = X, Z
    text = ",".join(b36(v) for v in out)
    with open(os.path.join(OUT, "net.js"), "w") as fh:
        fh.write("// GENERATED by tools/navi/build.py from Tampere Taxi Driver's map: the walking network.\n")
        fh.write("// Map data (c) OpenStreetMap contributors (ODbL), Tampereen kaupunki / Maanmittauslaitos (CC BY 4.0).\n")
        fh.write("export const NET = \"" + text + "\";\n")
    print(f"net: {len(keep)} nodes, {len(es)} edges, {len(text) // 1024} kB")


def main():
    if len(sys.argv) < 2:
        print(__doc__); sys.exit(2)
    d = ttd.read(sys.argv[1])
    os.makedirs(OUT, exist_ok=True)
    net(d)
    if "--no-tiles" not in sys.argv:
        have = tiles(d)
        meta = {"box": BOX, "tile": TILE, "levels": LEVELS, "have": have}
        with open(os.path.join(OUT, "mapinfo.js"), "w") as fh:
            fh.write("// GENERATED by tools/navi/build.py: where the map tiles are.\n")
            fh.write("export const MAP = " + json.dumps(meta, separators=(",", ":")) + ";\n")


main()
