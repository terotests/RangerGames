#!/usr/bin/env bash
# The Tietokoneet games (section "tietokoneet") and Oma kauppa (games/kauppa) use the Rakennuspelit kit
# (tools/rakennus/kit.tsx, kit.css) plus their own pictures (art.tsx) and a
# blue theme (theme.css). This copies them into each game as lib/kit.tsx and
# style.css (a game can only import files from its own folder).
set -euo pipefail
cd "$(dirname "$0")/../.."
for g in robotti omenalinja kauppa; do
  [[ -d games/$g ]] || continue
  mkdir -p games/$g/lib
  { echo "// GENERATED by tools/tietokoneet/sync.sh from tools/rakennus/kit.tsx + tools/tietokoneet/art.tsx: edit those, not this copy."; cat tools/rakennus/kit.tsx tools/tietokoneet/art.tsx; } > games/$g/lib/kit.tsx
  { echo "/* GENERATED by tools/tietokoneet/sync.sh from tools/rakennus/kit.css + tools/tietokoneet/theme.css */"; cat tools/rakennus/kit.css tools/tietokoneet/theme.css; if [[ -f games/$g/game.css ]]; then cat games/$g/game.css; fi; } > games/$g/style.css
done
echo synced
