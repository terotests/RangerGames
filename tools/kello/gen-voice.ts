function clips(lang: Lang): Record<string, string> {
  const out: Record<string, string> = {};
  for (const k of Object.keys(TEXT)) out[k] = TEXT[k][lang];
  for (const t of allTimes()) {
    const w = words(t, lang);
    out[clip(t)] = sentence(t, lang);
    out["kel_w_" + t.h + "_" + t.m] = w.charAt(0).toUpperCase() + w.slice(1) + ".";
  }
  return out;
}

// voice/fi.json: replace the kel_ clips (and peli_kello), keep the rest in order
const fiPath = "voice/fi.json";
const fi = JSON.parse(fs.readFileSync(fiPath, "utf8"));
for (const k of Object.keys(fi.clips)) if (k.startsWith("kel_") || k === "peli_kello") delete fi.clips[k];
Object.assign(fi.clips, clips("fi"));
fs.writeFileSync(fiPath, JSON.stringify(fi, null, 1) + "\n");

for (const lang of ["en", "es"] as Lang[]) {
  const doc = {
    _comment: "Kello (games/kello): generated by tools/kello/gen-voice.ts, same ids as voice/fi.json.",
    lang,
    clips: clips(lang),
  };
  fs.writeFileSync("voice/" + lang + "/kello.json", JSON.stringify(doc, null, 1) + "\n");
}
