#!/usr/bin/env python3
"""Muuttolintu: writes games/muutto/lib/world.ts and the m_* voice clips.

    python3 tools/muutto/build.py

The country outlines come from Kopterilento's games/kopteri/lib/world.ts
(Natural Earth 1:110m, public domain; tools/kopteri/build.py makes it).
The clips go into voice/fi.json (ids m_*); the build scripts render them.
"""
import json, os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")

# the species: id, name, the wintering country (id, Finnish name, in which),
# a sentence about its trip and one for arriving there
SPECIES = [
    ("joutsen", "Laulujoutsen", "DNK", "Tanska", "Tanskassa",
     "Laulujoutsen on Suomen kansallislintu. Se talvehtii lähellä, Tanskassa.",
     "Perillä! Tanskassa meri ei jäädy talvella, ja joutsen löytää ruokaa."),
    ("kurki", "Kurki", "ETH", "Etiopia", "Etiopiassa",
     "Kurki lentää Unkarin ja Egyptin kautta Afrikkaan, Etiopiaan.",
     "Perillä! Etiopiassa on lämmin koko vuoden."),
    ("paasky", "Haarapääsky", "ZAF", "Etelä-Afrikka", "Etelä-Afrikassa",
     "Haarapääsky lentää Euroopan ja Saharan yli Etelä-Afrikkaan asti.",
     "Perillä! Kun Suomessa on talvi, Etelä-Afrikassa on kesä."),
    ("tiira", "Lapintiira", "ATA", "Etelämanner", "Etelämantereella",
     "Lapintiira lentää pisimmän matkan kaikista linnuista, Etelämantereelle asti.",
     "Perillä! Kun Suomessa on talvi, Etelämantereella on kesä, ja aurinko paistaa yölläkin."),
]


def world():
    src = open(os.path.join(ROOT, "games", "kopteri", "lib", "world.ts")).read()
    line = next(l for l in src.split("\n") if l.startswith("export const REGIONS"))
    out = os.path.join(ROOT, "games", "muutto", "lib", "world.ts")
    with open(out, "w") as o:
        o.write("// GENERATED by tools/muutto/build.py from games/kopteri/lib/world.ts.\n")
        o.write("// Country outlines: Natural Earth 1:110m (public domain), naturalearthdata.com.\n")
        o.write("// Rings are [lon, lat, ...] in tenths of a degree.\n")
        o.write(line + "\n")
    print("%s: %d KB" % (out, os.path.getsize(out) // 1024))


def voice():
    path = os.path.join(ROOT, "voice", "fi.json")
    d = json.load(open(path))
    clips = d["clips"]
    for k in [k for k in clips if k.startswith("m_")]:
        del clips[k]
    c = {
        "peli_muutto": "Muuttolintu",
        "m_tervetuloa": "Olet muuttolintu. Valitse lintu!",
        "m_kevat": "Nyt on kevät. Lennä Suomeen pesimään!",
        "m_suomi": "Lennä Suomeen.",
        "m_perilla_suomi": "Perillä Suomessa!",
        "m_lunta_suomessa": "Suomessa on vielä lunta. Odotetaan, että kevät tulee.",
        "m_kevat_tuli": "Lumi suli. Nyt on kesä!",
        "m_pesa": "Rakenna pesä ja ruoki poikaset. Napauta poikasia!",
        "m_munat": "Munista kuoriutui poikasia!",
        "m_isoja": "Poikaset kasvoivat isoiksi. Ne osaavat lentää!",
        "m_syksy": "Nyt on syksy. Talvi tulee. Lennä etelään!",
        "m_kylma_kevat": "Brr, täällä on vielä talvi! Kevät ei ole vielä tullut.",
        "m_kylma_syksy": "Brr, talvi tuli! Lennä nopeasti etelään!",
        "m_nalka": "Lintu on nälkäinen. Syö ruokaa matkalla!",
        "m_namia": "Nam!",
        "m_valmis": "Hienoa! Lensit koko vuoden ympäri.",
        "m_aurinko": "Kesällä aurinko paistaa korkealta, ja talvella matalalta.",
        "m_kesa_suomi": "Suomessa on nyt kesä. Aurinko paistaa yölläkin.",
        "m_talvi_suomi": "Suomessa on nyt talvi ja pimeää.",
        "m_reitti": "Seuraa pisteitä. Ne näyttävät linnun oikean reitin.",
    }
    for sid, name, cid, cname, cin, fact, there in SPECIES:
        c["m_" + sid] = name + "."
        c["m_" + sid + "_tieto"] = fact
        c["m_" + sid + "_etela"] = "Lennä talveksi: %s." % cname
        c["m_" + sid + "_perilla"] = there
    clips.update(c)
    with open(path, "w") as o:
        json.dump(d, o, ensure_ascii=False, indent=1)
        o.write("\n")
    print("voice/fi.json: %d m_* clips" % len(c))


if __name__ == "__main__":
    world()
    voice()
