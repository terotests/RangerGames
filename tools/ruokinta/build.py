#!/usr/bin/env python3
"""Build the photos of games/ruokinta (Ruoki eläimet).

    python3 tools/ruokinta/fetch_commons.py   # where Wikimedia Commons is reachable -> tools/ruokinta/raw/
    python3 tools/ruokinta/build.py           # -> games/ruokinta/img/*.jpg, lib/photos.ts, CREDITS.md

The animals' photos are the living-animal photos of Kenen luut? (games/luut/img,
authors from games/luut/CREDITS.md); the foods and the animals missing there
come from pick.json (fetched into raw/ with meta.json). pick.json may give a
crop box [x0, y0, x1, y1] as fractions of the photo. Only CC0 / public domain /
CC BY / CC BY-SA photos are accepted.
"""
import json, os, re, sys, shutil
from PIL import Image, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
GAME = os.path.join(ROOT, "games", "ruokinta")
LUUT = os.path.join(ROOT, "games", "luut")
RAW = os.path.join(HERE, "raw")
W, H = 288, 216

OK = re.compile(r"^(cc0|cc[- ]by(-sa)?[- ]?[0-9.]*.*|public domain|pd.*)$", re.I)

def diet():
    src = open(os.path.join(GAME, "lib", "diet.ts"), encoding="utf-8").read()
    foods = re.findall(r'\{ id: "([a-z]+)", fi: "([^"]+)"', src.split("export const ANIMALS")[0])
    animals = re.findall(r'\{ id: "([a-z]+)", fi: "([^"]+)"', src.split("export const ANIMALS")[1].split("export const ANSWER")[0])
    return foods, animals

def luut_credits():
    out = {}
    for line in open(os.path.join(LUUT, "CREDITS.md"), encoding="utf-8"):
        m = re.match(r"^\| ([A-ZÄÖ][a-zäö]+) \| (.*) \| (.*) \| \[(File:.+?)\]\((.+)\) \|$", line)
        if m: out[m.group(1)] = {"author": m.group(2), "license": m.group(3), "file": m.group(4), "page": m.group(5)}
    return out

def fit(src, dst, crop=None):
    im = ImageOps.exif_transpose(Image.open(src)).convert("RGB")
    if crop:
        w, h = im.size
        im = im.crop((int(crop[0] * w), int(crop[1] * h), int(crop[2] * w), int(crop[3] * h)))
    im = ImageOps.fit(im, (W, H), Image.LANCZOS, centering=(0.5, 0.5))
    im.save(dst, "JPEG", quality=84, optimize=True, progressive=True)

def main():
    foods, animals = diet()
    pick = json.load(open(os.path.join(HERE, "pick.json"), encoding="utf-8"))
    meta = json.load(open(os.path.join(RAW, "meta.json"), encoding="utf-8"))
    lc = luut_credits()
    os.makedirs(os.path.join(GAME, "img"), exist_ok=True)
    photo, credits = {}, []
    names = {}
    for key, fi in animals: names[key] = fi
    for key, fi in foods: names[key] = fi
    for key, fi in animals + foods:
        dst = os.path.join(GAME, "img", key + ".jpg")
        if key in pick:
            m = meta[key]
            assert m["title"] == pick[key]["file"], key
            lic = m["license"]
            if not OK.match(lic) or re.search(r"\b(nc|nd)\b", lic.lower()): sys.exit("bad licence %s %s" % (key, lic))
            fit(os.path.join(RAW, key + ".jpg"), dst, pick[key].get("crop"))
            c = {"author": re.sub(r"\s+", " ", m["artist"]).strip(), "license": lic, "file": m["title"], "page": m["page"]}
        else:
            # the animal's photo from Kenen luut? (already cropped to 288 x 216)
            lname = {"pollo": "Pöllö"}.get(key, fi)
            shutil.copyfile(os.path.join(LUUT, "img", key + ".jpg"), dst)
            c = lc[lname]
        photo[key] = {"f": "img/%s.jpg" % key, "c": "%s · %s" % (c["author"], c["license"])}
        credits.append({"what": names[key], "author": c["author"], "license": c["license"], "file": c["file"], "page": c["page"]})
    with open(os.path.join(GAME, "lib", "photos.ts"), "w", encoding="utf-8") as f:
        f.write("// GENERATED by tools/ruokinta/build.py. Photos: Wikimedia Commons, see ../CREDITS.md\n")
        f.write("export const PHOTO: any = %s;\n" % json.dumps(photo, ensure_ascii=False))
        f.write("export const CREDITS: any[] = %s;\n" % json.dumps([{k: c[k] for k in ("what", "author", "license", "file")} for c in credits], ensure_ascii=False))
    with open(os.path.join(GAME, "CREDITS.md"), "w", encoding="utf-8") as f:
        f.write("# Ruoki eläimet – kuvien tekijät\n\n")
        f.write("Kaikki kuvat ovat Wikimedia Commonsista. Eläinten kuvat ovat samat kuin Kenen luut? -pelissä (`games/luut`). "
                "Kuvia on rajattu ja pienennetty peliä varten (muutokset: rajaus ja koko). Lisenssit: CC0 / public domain, CC BY ja CC BY-SA; "
                "CC BY-SA -kuvien muokatut versiot jaetaan samalla lisenssillä.\n\n")
        f.write("| Kuva | Tekijä | Lisenssi | Lähde |\n| --- | --- | --- | --- |\n")
        for c in credits:
            f.write("| %s | %s | %s | [%s](%s) |\n" % (c["what"], c["author"].replace("|", "/"), c["license"], c["file"], c["page"]))
    print(len(photo), "photos")

main()
