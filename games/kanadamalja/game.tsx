// ---- the phone's moves ---------------------------------------------------
function distFrom(target: number): number[] {
  const d: number[] = [];
  for (let i = 0; i < NODES.length; i++) d.push(9999);
  d[target] = 0;
  const q = [target];
  while (q.length) {
    const n = q.shift() as number;
    for (const m of ADJ[n]) if (d[m] > d[n] + 1) { d[m] = d[n] + 1; q.push(m); }
  }
  return d;
}

function aiTarget(): number {
  const p = P();
  if (p.malja || p.winMakkara) return ARENA;
  const o = players[1 - cur];
  const d = distFrom(p.node);
  if (o.malja && !o.jail && d[o.node] <= 8) return o.node;
  let best = -1, bd = 9999;
  for (let i = 0; i < PLACES.length; i++) {
    if (!tokens[i]) continue;
    const v = d[i] - (i === SARKANNIEMI ? 4 : 0) + rg.random() * 2;
    if (v < bd) { bd = v; best = i; }
  }
  return best >= 0 ? best : ARENA;
}

function aiStep() {
  const p = P();
  if (phase === "start") { chooseStart(rg.pick(STARTS)); return; }
  if (phase === "jail") {
    if (luckFailed) { endTurn(); return; }
    if (p.makkara > 0) jailMakkara();
    else if (p.money >= FINE + 200) jailPay();
    else roll("jail");
    return;
  }
  if (phase === "turn") {
    const here = placeOf(p.node);
    if (here >= 0 && tokens[here]) { phase = "ask"; aiClock = 0; return; }
    const target = aiTarget();
    const dist = distFrom(target);
    const reserve = p.malja || p.winMakkara ? 0 : OPEN_PRICE;
    let best: Dest | null = null, gain = 5;
    for (const d of rideDests()) {
      if (d.price > p.money - reserve) continue;
      const g = dist[p.node] - dist[d.node];
      if (g > gain) { gain = g; best = d; }
    }
    if (best) { go(best); return; }
    roll("move");
    return;
  }
  if (phase === "choose" || phase === "tram") {
    const target = aiTarget();
    const dist = distFrom(target);
    let best = dests[0], bv = 99999;
    for (const d of dests) {
      const pl = placeOf(d.node);
      const v = dist[d.node] - (pl >= 0 && tokens[pl] ? 1.5 : 0) + d.price / 100;
      if (v < bv) { bv = v; best = d; }
    }
    go(best);
    return;
  }
  if (phase === "ask") {
    if (luckFailed) { endTurn(); return; }
    if (p.money >= OPEN_PRICE && (p.money >= 300 || rg.random() < 0.5)) pay(); else roll("luck");
    return;
  }
  if (phase === "reveal" && reveal.clock > 2.2) revealDone();
}

// ---- frame -----------------------------------------------------------------
function tick(dt: number, input: any) {
  t += dt; pulse += dt;
  panStep(input);
  if (phase === "rolling") {
    const before = rollClock;
    rollClock += dt;
    // a knock at every landing of the bounces
    if (before < ROLL_T && Math.floor(rollClock / ROLL_T * 3) !== Math.floor(before / ROLL_T * 3)) {
      rg.sound("hit", { pitch: 1.3 + Math.floor(rollClock / ROLL_T * 3) * 0.15, volume: 0.6 });
      rg.vibrate(15);
    }
    if (rollClock >= ROLL_T + HOLD_T) rolled();
  }
  if (phase === "moving") {
    const sp = moving.kind === "walk" ? 5.5 : moving.kind === "police" ? 1.6 : 2.6;
    moving.u += dt * sp;
    while (moving.u >= 1 && phase === "moving") {
      moving.u -= 1;
      moving.i++;
      const n = moving.path[moving.i];
      P().node = n;
      if (moving.kind === "walk") rg.sound("pop", { pitch: 1.2 + (moving.i % 2) * 0.15, volume: 0.5 });
      if (moving.i >= moving.path.length - 1) {
        if (moving.kind === "police") endTurn(); else arrive();
      }
    }
  }
  if (phase === "reveal") reveal.clock += dt;
  if (phase === "win") winClock += dt;
  if (players.length) camStep(dt);
  if (players.length && P().ai && (phase === "start" || phase === "turn" || phase === "choose" || phase === "tram" || phase === "ask" || phase === "jail" || phase === "reveal")) {
    aiClock += dt;
    if (aiClock > 1.0) { aiClock = 0; aiStep(); }
  }
}

