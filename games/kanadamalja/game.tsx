// Kanada-malja: a treasure-hunt board game in Tampere for two (Ilves and
// Tappara), on one phone or against the phone.
//
// Every big place on the board has a face-down token. Roll the die, choose
// where to go, and open the token where you stop: pay 100 €, or try your luck
// (4, 5 or 6 opens it for free). Under the tokens: the Kanada-malja, hockey
// cards (Kummola 300 €, Raipe 600 €, Barkov 1000 €), mustamakkara (worth
// little, but it gets you out of the Sori jail; one found after the cup has
// been found wins like the cup), robbers who take all your money, the police
// who take you to Sori, and empty tokens. In Särkänniemi everything comes
// double. The tram and the boats are faster but cost money. Whoever first
// brings the cup (or a winning sausage) to Nokia Areena wins.
//
// The board is generated by tools/kanadamalja/build.py (lib/board.ts, img/).

import { BOARD } from "lib/board";

type Team = "ilves" | "tappara";
type Player = { team: Team; node: number; money: number; malja: boolean; makkara: number; winMakkara: boolean; jail: boolean; ai: boolean };
type Phase = "menu" | "pick" | "rules" | "turn" | "rolling" | "choose" | "moving" | "ask" | "reveal" | "tram" | "jail" | "win";
type Dest = { node: number; path: number[]; price: number; kind: string };

const PLACES: any[] = BOARD.places;
const NODES: number[][] = BOARD.nodes;
const ADJ: number[][] = BOARD.adj;
const TRAMS: any[] = BOARD.trams;
const BOATS: any[] = BOARD.boats;
const ARENA = 0;
const SORI = PLACES.findIndex((p: any) => p.kind === "jail");
const SARKANNIEMI = PLACES.findIndex((p: any) => p.kind === "double");
const START_MONEY = 300;
const OPEN_PRICE = 100;
const FINE = 200;
const TOKENS: string[] = ["malja", "makkara", "makkara", "makkara", "rosvo", "rosvo", "rosvo", "poliisi", "poliisi",
  "barkov", "raipe", "raipe", "kummola", "kummola", "kummola", "kummola",
  "tyhja", "tyhja", "tyhja", "tyhja", "tyhja", "tyhja", "tyhja", "tyhja"];
const VALUE: any = { kummola: 300, raipe: 600, barkov: 1000 };
const TOPH = 62, BOTH = 150;

let phase: Phase = "menu";
let t = 0;
let players: Player[] = [];
let cur = 0;
let tokens: string[] = [];     // per place: the token still face down, or ""
let maljaFound = false;
let msg = "";
let dice = 0;                  // the die's face (0 = not rolled)
let rollClock = 0;
let rollFor = "";              // "move" | "luck" | "jail"
let dests: Dest[] = [];
let moving: { path: number[]; i: number; u: number; kind: string } = { path: [], i: 0, u: 0, kind: "" };
let reveal: { token: string; clock: number; text: string; place: number; luck: boolean } = { token: "", clock: 0, text: "", place: 0, luck: false };
let luckFailed = false;
let aiClock = 0;
let winner = -1;
let winClock = 0;
let pulse = 0;

function P(): Player { return players[cur]; }
function placeOf(node: number): number { return NODES[node][2]; }
function teamName(team: Team) { return team === "ilves" ? "Ilves" : "Tappara"; }
function clip(id: string) { rg.say("km_" + id); }

// ---- a new game, saving and loading ----------------------------------
function newGame(aiTeam: string) {
  players = [];
  const order: Team[] = aiTeam === "ilves" ? ["tappara", "ilves"] : ["ilves", "tappara"];
  for (const team of order) players.push({ team: team, node: ARENA, money: START_MONEY, malja: false, makkara: 0, winMakkara: false, jail: false, ai: team === aiTeam });
  const bag = rg.shuffle(TOKENS.slice());
  tokens = [];
  let k = 0;
  for (let i = 0; i < PLACES.length; i++) tokens.push(i === ARENA || i === SORI ? "" : bag[k++] || "tyhja");
  maljaFound = false; cur = 0; winner = -1;
  rg.sound("click");
  startTurn();
}

function save() {
  if (phase === "win" || phase === "menu") { rg.save("game", ""); return; }
  rg.save("game", JSON.stringify({ players: players, cur: cur, tokens: tokens, maljaFound: maljaFound }));
}

function resume() {
  const s = rg.load("game", "");
  if (!s) return;
  const g = JSON.parse(s);
  players = g.players; cur = g.cur; tokens = g.tokens; maljaFound = g.maljaFound; winner = -1;
  rg.sound("click");
  startTurn();
}

// ---- turns -------------------------------------------------------------
function startTurn() {
  dice = 0; dests = []; aiClock = 0; luckFailed = false;
  const p = P();
  if (p.jail) {
    phase = "jail";
    msg = rg.t(teamName(p.team) + " on Sorin putkassa.", teamName(p.team) + " is in the Sori jail.", teamName(p.team) + " está en la cárcel de Sori.");
    rg.say(["km_vuoro_" + p.team, "km_putka"], {});
  } else {
    phase = "turn";
    msg = rg.t(teamName(p.team) + ": heitä noppaa!", teamName(p.team) + ": roll the die!", teamName(p.team) + ": ¡tira el dado!");
    clip("vuoro_" + p.team);
  }
  save();
}

function endTurn() {
  cur = 1 - cur;
  startTurn();
}

function roll(purpose: string) {
  rollFor = purpose; rollClock = 0; phase = "rolling"; aiClock = 0;
  dice = rg.range(1, 6);
  rg.sound("whoosh");
  rg.vibrate(20);
}

function rolled() {
  const p = P();
  rg.sound("pop", { pitch: 0.8 + dice * 0.1 });
  if (rollFor !== "move" || P().ai) rg.say(rg.sayId.number(dice));
  if (rollFor === "luck") {
    if (dice >= 4) { openToken(placeOf(p.node), true); }
    else {
      luckFailed = true;
      msg = rg.t("Ei onnistunut. Vuoro vaihtuu.", "No luck. Next turn.", "Sin suerte. Siguiente turno.");
      rg.sound("wrong");
      phase = "ask"; aiClock = 0;
    }
    return;
  }
  if (rollFor === "jail") {
    if (dice >= 5) {
      p.jail = false;
      clip("vapaa");
      rg.sound("coin");
    } else {
      msg = rg.t("Ei viitosta eikä kuutosta. Odota putkassa.", "No five or six. Wait in jail.", "Ni cinco ni seis. Espera en la cárcel.");
      rg.sound("wrong");
      phase = "jail"; luckFailed = true; aiClock = 0;
      return;
    }
  }
  dests = walkDests(p.node, dice);
  phase = "choose"; aiClock = 0;
  msg = rg.t("Sait " + dice + ". Valitse, minne siirryt.", "You got " + dice + ". Choose where to go.", "Sacaste " + dice + ". Elige adónde ir.");
  if (!p.ai) rg.say([rg.sayId.number(dice), "km_valitse"]);
}

// every node `steps` steps away along the paths, and every place on the way
// (a place can be stopped at early); no node twice on one move
function walkDests(from: number, steps: number): Dest[] {
  const found: any = {};
  const out: Dest[] = [];
  const path: number[] = [from];
  const go = (n: number, left: number) => {
    if (n !== from && (left === 0 || placeOf(n) >= 0) && !found[n]) {
      found[n] = true;
      out.push({ node: n, path: path.slice(), price: 0, kind: "walk" });
    }
    if (left === 0) return;
    for (const m of ADJ[n]) {
      if (path.indexOf(m) >= 0) continue;
      path.push(m);
      go(m, left - 1);
      path.pop();
    }
  };
  go(from, steps);
  return out;
}

function fare(stops: number): number {
  for (const f of BOARD.fares) if (stops <= f[0]) return f[1];
  return 150;
}

// tram and boat rides from the place the player stands on
function rideDests(): Dest[] {
  const p = P();
  const here = placeOf(p.node);
  const out: Dest[] = [];
  if (here < 0) return out;
  for (const line of TRAMS) {
    const i = line.stops.indexOf(here);
    if (i < 0) continue;
    for (let j = 0; j < line.stops.length; j++) {
      if (j === i) continue;
      const price = fare(Math.abs(j - i));
      const path: number[] = [];
      const dir = j > i ? 1 : -1;
      for (let k = i; k !== j + dir; k += dir) path.push(line.stops[k]);
      const old = out.findIndex((d) => d.node === line.stops[j]);
      if (old >= 0) { if (out[old].price <= price) continue; out.splice(old, 1); }
      out.push({ node: line.stops[j], path: path, price: price, kind: "tram" });
    }
  }
  for (const b of BOATS) {
    if (b.a === here || b.b === here) out.push({ node: b.a === here ? b.b : b.a, path: [here, b.a === here ? b.b : b.a], price: b.price, kind: "boat" });
  }
  return out;
}

function canRide(): boolean {
  const p = P();
  return rideDests().some((d) => d.price <= p.money);
}

function startRide() {
  const p = P();
  dests = rideDests().filter((d) => d.price <= p.money);
  if (!dests.length) return;
  phase = "tram"; aiClock = 0;
  msg = rg.t("Ratikka ja laiva: valitse pysäkki.", "Tram and boat: choose a stop.", "Tranvía y barco: elige una parada.");
  rg.sound("note");
  if (!p.ai) clip("ratikka_valitse");
}

function go(d: Dest) {
  const p = P();
  if (d.price > 0) {
    p.money -= d.price;
    rg.sound("coin", { pitch: 0.8 });
    clip(d.kind === "boat" ? "laiva" : "ratikka");
  } else rg.sound("click");
  moving = { path: d.path, i: 0, u: 0, kind: d.kind };
  phase = "moving";
  dests = [];
}

function arrive() {
  const p = P();
  const pl = placeOf(p.node);
  if (pl === ARENA && (p.malja || p.winMakkara)) { win(); return; }
  if (pl >= 0) {
    if (tokens[pl]) {
      phase = "ask"; aiClock = 0;
      msg = rg.t(PLACES[pl].name + ": avataanko nappi?", PLACES[pl].name + ": open the token?", PLACES[pl].name + ": ¿abrir la ficha?");
      rg.say(["km_p_" + PLACES[pl].id, "km_avaa"]);
      return;
    }
    rg.say("km_p_" + PLACES[pl].id);
  }
  endTurn();
}

function openToken(pl: number, luck: boolean) {
  const p = P();
  const token = tokens[pl];
  tokens[pl] = "";
  const double = pl === SARKANNIEMI;
  let text = "";
  let say: string[] = [];
  if (token === "malja") {
    p.malja = true; maljaFound = true;
    text = rg.t("Kanada-malja! Vie se Nokia Areenalle!", "The Kanada Cup! Take it to Nokia Areena!", "¡La Copa Kanada! ¡Llévala al Nokia Areena!");
    say = ["km_malja"];
  } else if (token === "makkara") {
    if (maljaFound) {
      p.winMakkara = true;
      text = rg.t("Mustamakkara! Kun malja on jo löytynyt, makkarakin kelpaa: vie se Nokia Areenalle ennen maljaa!", "Black sausage! Now that the cup is found, it counts too: take it to Nokia Areena before the cup gets there!", "¡Morcilla! Ahora que la copa está encontrada, también vale: ¡llévala al Nokia Areena antes que la copa!");
      say = ["km_makkara_voitto"];
    } else {
      p.makkara += double ? 2 : 1;
      text = rg.t("Mustamakkara" + (double ? " tuplana" : "") + ". Ei paljon arvoa, mutta sillä pääsee pois Sorin putkasta.", "Black sausage" + (double ? ", two of them" : "") + ". Not worth much, but it gets you out of the Sori jail.", "Morcilla" + (double ? " doble" : "") + ". No vale mucho, pero te saca de la cárcel de Sori.");
      say = ["km_makkara"];
    }
  } else if (VALUE[token]) {
    const v = VALUE[token] * (double ? 2 : 1);
    p.money += v;
    text = (token === "kummola" ? "Kummola" : token === "raipe" ? "Raipe" : "Barkov") + "! +" + v + " €" + (double ? rg.t(" (Särkänniemessä tuplana!)", " (double in Särkänniemi!)", " (¡doble en Särkänniemi!)") : "");
    say = ["km_" + token];
    if (double) say.push("km_tupla");
  } else if (token === "rosvo") {
    const had = p.money;
    p.money = 0;
    text = had > 0 ? rg.t("Rosvo vei kaikki rahasi (" + had + " €)!", "A robber took all your money (" + had + " €)!", "¡Un ladrón se llevó todo tu dinero (" + had + " €)!")
      : rg.t("Rosvo! Onneksi sinulla ei ollut rahaa.", "A robber! Luckily you had no money.", "¡Un ladrón! Por suerte no tenías dinero.");
    say = ["km_rosvo"];
  } else if (token === "poliisi") {
    text = rg.t("Poliisi! Joudut Sorin putkaan.", "Police! You go to the Sori jail.", "¡Policía! Vas a la cárcel de Sori.");
    say = ["km_poliisi"];
  } else {
    text = rg.t("Tyhjä nappi.", "An empty token.", "Una ficha vacía.");
    say = ["km_tyhja"];
  }
  reveal = { token: token, clock: 0, text: text, place: pl, luck: luck };
  phase = "reveal"; aiClock = 0;
  rg.say(say);
  if (token === "malja" || token === "barkov" || (token === "makkara" && maljaFound)) { rg.celebrate(width / 2, height * 0.42, { big: true }); rg.vibrate([60, 40, 120]); }
  else if (VALUE[token]) { rg.sound("coin"); rg.celebrate(width / 2, height * 0.42, {}); }
  else if (token === "rosvo" || token === "poliisi") { rg.sound("lose"); rg.vibrate(200); }
  else rg.sound("pop");
}

function revealDone() {
  const p = P();
  if (reveal.token === "poliisi") {
    p.jail = true;
    moving = { path: [p.node, SORI], i: 0, u: 0, kind: "police" };
    phase = "moving";
    return;
  }
  endTurn();
}

function pay() {
  const p = P();
  if (p.money < OPEN_PRICE) return;
  p.money -= OPEN_PRICE;
  rg.sound("coin", { pitch: 0.7 });
  openToken(placeOf(p.node), false);
}

function jailPay() {
  const p = P();
  if (p.money < FINE) return;
  p.money -= FINE; p.jail = false;
  rg.sound("coin", { pitch: 0.7 }); clip("vapaa");
  phase = "turn"; aiClock = 0;
  msg = rg.t("Vapaa! Heitä noppaa.", "Free! Roll the die.", "¡Libre! Tira el dado.");
}

function jailMakkara() {
  const p = P();
  if (p.makkara < 1) return;
  p.makkara--; p.jail = false;
  rg.sound("pop"); clip("makkara_vapaa");
  phase = "turn"; aiClock = 0;
  msg = rg.t("Vartija sai makkaran. Vapaa! Heitä noppaa.", "The guard got the sausage. Free! Roll the die.", "El guardia recibió la morcilla. ¡Libre! Tira el dado.");
}

function win() {
  winner = cur; winClock = 0; phase = "win";
  rg.celebrate(width / 2, height * 0.4, { big: true });
  rg.sound("win"); rg.vibrate([80, 60, 80, 60, 200]);
  clip("voitti_" + P().team);
  rg.save("game", "");
}

// ---- the phone's moves ---------------------------------------------------
function distFrom(target: number): number[] {
  const d: number[] = [];
  for (let i = 0; i < NODES.length; i++) d.push(9999);
  d[target] = 0;
  const q = [target];
  while (q.length) {
    const n = q.shift() as number;
    for (const m of ADJ[n]) if (d[m] > d[n] + 1) { d[m] = d[n] + 1; q.push(m); }
  }
  return d;
}

function aiTarget(): number {
  const p = P();
  if (p.malja || p.winMakkara) return ARENA;
  const d = distFrom(p.node);
  let best = -1, bd = 9999;
  for (let i = 0; i < PLACES.length; i++) {
    if (!tokens[i]) continue;
    const v = d[i] - (i === SARKANNIEMI ? 4 : 0) + rg.random() * 2;
    if (v < bd) { bd = v; best = i; }
  }
  return best >= 0 ? best : ARENA;
}

function aiStep() {
  const p = P();
  if (phase === "jail") {
    if (luckFailed) { endTurn(); return; }
    if (p.makkara > 0) jailMakkara();
    else if (p.money >= FINE + 200) jailPay();
    else roll("jail");
    return;
  }
  if (phase === "turn") {
    const here = placeOf(p.node);
    if (here >= 0 && tokens[here]) { phase = "ask"; aiClock = 0; return; }
    const target = aiTarget();
    const dist = distFrom(target);
    const reserve = p.malja || p.winMakkara ? 0 : OPEN_PRICE;
    let best: Dest | null = null, gain = 5;
    for (const d of rideDests()) {
      if (d.price > p.money - reserve) continue;
      const g = dist[p.node] - dist[d.node];
      if (g > gain) { gain = g; best = d; }
    }
    if (best) { go(best); return; }
    roll("move");
    return;
  }
  if (phase === "choose" || phase === "tram") {
    const target = aiTarget();
    const dist = distFrom(target);
    let best = dests[0], bv = 99999;
    for (const d of dests) {
      const pl = placeOf(d.node);
      const v = dist[d.node] - (pl >= 0 && tokens[pl] ? 1.5 : 0) + d.price / 100;
      if (v < bv) { bv = v; best = d; }
    }
    go(best);
    return;
  }
  if (phase === "ask") {
    if (luckFailed) { endTurn(); return; }
    if (p.money >= OPEN_PRICE && (p.money >= 300 || rg.random() < 0.5)) pay(); else roll("luck");
    return;
  }
  if (phase === "reveal" && reveal.clock > 2.2) revealDone();
}

// ---- frame -----------------------------------------------------------------
function tick(dt: number) {
  t += dt; pulse += dt;
  if (phase === "rolling") {
    rollClock += dt;
    if (rollClock < 0.8 && Math.floor(rollClock * 14) !== Math.floor((rollClock - dt) * 14)) rg.sound("tick", { pitch: 1 + rg.random() * 0.4 });
    if (rollClock >= 0.8) rolled();
  }
  if (phase === "moving") {
    const sp = moving.kind === "walk" ? 5.5 : moving.kind === "police" ? 1.6 : 2.6;
    moving.u += dt * sp;
    while (moving.u >= 1 && phase === "moving") {
      moving.u -= 1;
      moving.i++;
      const n = moving.path[moving.i];
      P().node = n;
      if (moving.kind === "walk") rg.sound("pop", { pitch: 1.2 + (moving.i % 2) * 0.15, volume: 0.5 });
      if (moving.i >= moving.path.length - 1) {
        if (moving.kind === "police") endTurn(); else arrive();
      }
    }
  }
  if (phase === "reveal") reveal.clock += dt;
  if (phase === "win") winClock += dt;
  if (players.length && P().ai && (phase === "turn" || phase === "choose" || phase === "tram" || phase === "ask" || phase === "jail" || phase === "reveal")) {
    aiClock += dt;
    if (aiClock > 1.0) { aiClock = 0; aiStep(); }
  }
}

function onBack() {
  if (phase === "menu") rg.exit();
  else if (phase === "pick" || phase === "rules") phase = "menu";
  else { save(); phase = "menu"; }
}

// ---- drawing ---------------------------------------------------------------
function layout() {
  const avail = height - TOPH - BOTH;
  const k = Math.min(width / BOARD.W, avail / BOARD.H);
  const bw = BOARD.W * k, bh = BOARD.H * k;
  return { k: k, x: (width - bw) / 2, y: TOPH + (avail - bh) / 2, w: bw, h: bh };
}

function pawnPos(i: number): number[] {
  const p = players[i];
  let x = NODES[p.node][0], y = NODES[p.node][1], lift = 0;
  if (phase === "moving" && i === cur && moving.i < moving.path.length - 1) {
    const a = NODES[moving.path[moving.i]], b = NODES[moving.path[moving.i + 1]];
    const u = moving.kind === "walk" ? moving.u : rg.ease.inOut(moving.u);
    x = a[0] + (b[0] - a[0]) * u; y = a[1] + (b[1] - a[1]) * u;
    if (moving.kind === "walk") lift = Math.sin(u * Math.PI) * 7;
  }
  const other = players[1 - i];
  if (other && other.node === p.node && !(phase === "moving" && (i === cur || 1 - i === cur))) x += i === 0 ? -7 : 7;
  return [x, y, lift];
}

function boardTap(info: any) {
  if (P().ai || (phase !== "choose" && phase !== "tram")) return;
  const L = layout();
  let best: Dest | null = null, bd = 30;
  for (const d of dests) {
    const n = NODES[d.node];
    const dd = Math.hypot(L.x + n[0] * L.k - info.x, L.y + n[1] * L.k - info.y);
    if (dd < bd) { bd = dd; best = d; }
  }
  if (best) go(best);
}

function Board() {
  const L = layout();
  const k = L.k;
  const out: any[] = [];
  out.push(<img className="board" id="board" src={rg.asset("img/board.png")} style={{ left: 0, top: 0, width: L.w, height: L.h }} onClick={boardTap} />);
  // destinations: pulsing rings (and the fare on rides)
  const s = 1 + Math.sin(pulse * 6) * 0.12;
  for (const d of dests) {
    const n = NODES[d.node];
    const r = (placeOf(d.node) >= 0 ? 16 : 10) * k * s;
    out.push(<div className={d.kind === "walk" ? "dest" : "dest ride"} style={{ left: n[0] * k - r, top: n[1] * k - r, width: r * 2, height: r * 2, borderRadius: r }} />);
    if (d.price > 0) out.push(<div className="fare" style={{ left: n[0] * k - 22, top: n[1] * k - 15 * k - 20 }}>{(d.kind === "boat" ? "⛴ " : "🚋 ") + d.price + " €"}</div>);
  }
  const ts = 20 * k;
  for (let i = 0; i < PLACES.length; i++) {
    if (!tokens[i]) continue;
    out.push(<img className="tok" src={rg.asset("img/puck.png")} style={{ left: PLACES[i].x * k - ts / 2, top: PLACES[i].y * k - ts / 2 - 1, width: ts, height: ts }} />);
  }
  // pawns, the one whose turn it is on top
  const order = [1 - cur, cur];
  for (const i of order) {
    if (!players[i]) continue;
    const pos = pawnPos(i);
    const ps = (i === cur ? 30 : 26) * k;
    const bob = i === cur && (phase === "turn" || phase === "choose") ? Math.abs(Math.sin(t * 4)) * 3 : 0;
    out.push(<img className="pawn" src={rg.asset("img/" + players[i].team + ".png")} style={{ left: pos[0] * k - ps / 2, top: pos[1] * k - ps * 0.85 - (pos[2] + bob) * k, width: ps, height: ps }} />);
    if (players[i].malja) out.push(<img className="pawn" src={rg.asset("img/malja.png")} style={{ left: pos[0] * k + ps * 0.15, top: pos[1] * k - ps * 1.25 - (pos[2] + bob) * k, width: ps * 0.6, height: ps * 0.6 }} />);
    if (phase === "moving" && i === cur && moving.kind !== "walk") out.push(<div className="vehicle" style={{ left: pos[0] * k - 14, top: pos[1] * k + 2 }}>{moving.kind === "boat" ? "⛴" : moving.kind === "police" ? "🚓" : "🚋"}</div>);
  }
  return <div className="boardbox" style={{ left: L.x, top: L.y, width: L.w, height: L.h }}>{out}</div>;
}

function PlayerPanel(i: number) {
  const p = players[i];
  const on = i === cur && phase !== "win";
  const items: any[] = [];
  if (p.malja) items.push(<img className="item" src={rg.asset("img/malja.png")} />);
  if (p.winMakkara) items.push(<img className="item gold" src={rg.asset("img/makkara.png")} />);
  for (let m = 0; m < Math.min(p.makkara, 3); m++) items.push(<img className="item" src={rg.asset("img/makkara.png")} />);
  if (p.jail) items.push(<div className="jailtag">🔒</div>);
  return (
    <div className={"panel " + p.team + (on ? " on" : "")} style={{ width: (width - 64) / 2 }}>
      <img className="ppawn" src={rg.asset("img/" + p.team + ".png")} />
      <div className="pcol">
        <div className="pname">{teamName(p.team) + (p.ai ? " 📱" : "")}</div>
        <div className="prow"><div className="money">{p.money + " €"}</div>{items}</div>
      </div>
    </div>
  );
}

function Dice() {
  if (!dice) return null;
  const face = phase === "rolling" ? 1 + Math.floor(rollClock * 14 * 7) % 6 : dice;
  const spots: any = { 1: [4], 2: [0, 8], 3: [0, 4, 8], 4: [0, 2, 6, 8], 5: [0, 2, 4, 6, 8], 6: [0, 2, 3, 5, 6, 8] };
  const cells: any[] = [];
  for (let c = 0; c < 9; c++) cells.push(<div className="dcell">{spots[face].indexOf(c) >= 0 ? <div className="pip" /> : null}</div>);
  const rot = phase === "rolling" ? Math.round(Math.sin(rollClock * 30) * 20) : 0;
  return <div className="dice" style={{ transform: "rotate(" + rot + "deg)" }}>{cells}</div>;
}

function Btn(id: string, label: string, cls: string, on: () => void, enabled: boolean) {
  if (!enabled) return <div className={"btn off " + cls} id={id}>{label}</div>;
  return <div className={"btn " + cls} id={id} onClick={on}>{label}</div>;
}

function Bottom() {
  const p = P();
  const btns: any[] = [];
  const human = !p.ai;
  if (human && phase === "turn") {
    const here = placeOf(p.node);
    btns.push(Btn("roll", "🎲 " + rg.t("Heitä", "Roll", "Tirar"), "go", () => roll("move"), true));
    if (rideDests().length) btns.push(Btn("ride", "🚋 " + rg.t("Kyyti", "Ride", "Viaje"), "tram", startRide, canRide()));
    if (here >= 0 && tokens[here]) btns.push(Btn("open", "🔓 " + rg.t("Avaa", "Open", "Abrir"), "open", () => { phase = "ask"; luckFailed = false; msg = rg.t("Avataanko nappi?", "Open the token?", "¿Abrir la ficha?"); clip("avaa"); }, true));
  }
  if (human && phase === "tram") btns.push(Btn("cancel", rg.t("← Takaisin", "← Back", "← Atrás"), "back", () => { phase = "turn"; dests = []; }, true));
  return (
    <div className="bottom" style={{ top: height - BOTH, height: BOTH }}>
      <div className="msgrow">
        {Dice()}
        <div className={"msg " + p.team}>{msg}</div>
      </div>
      <div className="btnrow">{btns}</div>
    </div>
  );
}

function tokenImg(token: string) {
  return rg.asset("img/" + token + ".png");
}

function Dialog() {
  const p = P();
  const human = !p.ai;
  if (phase === "ask") {
    const pl = placeOf(p.node);
    const btns: any[] = [];
    if (luckFailed) {
      if (human) btns.push(Btn("ok", rg.t("Selvä", "OK", "Vale"), "go dbtn", endTurn, true));
    } else if (human) {
      btns.push(Btn("pay", "💶 " + rg.t("Maksa 100 €", "Pay 100 €", "Paga 100 €"), "go dbtn", pay, p.money >= OPEN_PRICE));
      btns.push(Btn("luck", "🎲 " + rg.t("Kokeile onnea: 4–6", "Try your luck: 4–6", "Prueba suerte: 4–6"), "tram dbtn", () => roll("luck"), true));
      btns.push(Btn("skip", rg.t("Ei nyt", "Not now", "Ahora no"), "back dbtn", endTurn, true));
    }
    return (
      <div className="dialog" style={{ left: (width - 300) / 2, top: TOPH + 40 }}>
        <div className="dtitle">{PLACES[pl].name}</div>
        <img className="bigpuck" src={rg.asset("img/puck.png")} />
        <div className="dtext">{luckFailed ? msg : rg.t("Nappi on kiinni. Avaa se maksamalla, tai kokeile onnea nopalla.", "The token is face down. Pay to open it, or try your luck with the die.", "La ficha está boca abajo. Paga para abrirla o prueba suerte con el dado.")}</div>
        {btns}
      </div>
    );
  }
  if (phase === "rolling" && rollFor !== "move") {
    return (
      <div className="dialog" style={{ left: (width - 300) / 2, top: TOPH + 40 }}>
        <div className="dtitle">{rollFor === "luck" ? rg.t("4, 5 tai 6 avaa!", "4, 5 or 6 opens!", "¡4, 5 o 6 abre!") : rg.t("5 tai 6 vapauttaa!", "5 or 6 sets you free!", "¡5 o 6 te libera!")}</div>
        <div className="bigdice">{Dice()}</div>
      </div>
    );
  }
  if (phase === "reveal") {
    const c = reveal.clock;
    // the puck flips: it narrows, then the find widens in its place
    const flip = c < 0.25 ? 1 - c / 0.25 : Math.min(1, (c - 0.25) / 0.25);
    const card = VALUE[reveal.token];
    const iw = (card ? 120 : 128) * flip, ih = card ? 168 : 128;
    const src = c < 0.25 ? rg.asset("img/puck.png") : tokenImg(reveal.token);
    return (
      <div className="dialog" style={{ left: (width - 300) / 2, top: TOPH + 30 }}>
        <div className="dtitle">{PLACES[reveal.place].name}</div>
        <div className="revbox" style={{ height: ih + 8 }}>
          <img src={src} style={{ width: Math.max(2, iw), height: c < 0.25 ? 128 : ih }} />
        </div>
        <div className="dtext">{c >= 0.25 ? reveal.text : ""}</div>
        {human && c > 0.6 ? Btn("ok", rg.t("Selvä!", "OK!", "¡Vale!"), "go dbtn", revealDone, true) : null}
      </div>
    );
  }
  if (phase === "jail") {
    const btns: any[] = [];
    if (luckFailed) { if (human) btns.push(Btn("ok", rg.t("Selvä", "OK", "Vale"), "go dbtn", endTurn, true)); }
    else if (human) {
      btns.push(Btn("fine", "💶 " + rg.t("Sakko " + FINE + " €", "Fine " + FINE + " €", "Multa " + FINE + " €"), "go dbtn", jailPay, p.money >= FINE));
      btns.push(Btn("sausage", "🌭 " + rg.t("Anna makkara", "Give a sausage", "Da una morcilla"), "open dbtn", jailMakkara, p.makkara > 0));
      btns.push(Btn("jroll", "🎲 " + rg.t("Heitä 5 tai 6", "Roll 5 or 6", "Saca 5 o 6"), "tram dbtn", () => roll("jail"), true));
    }
    return (
      <div className="dialog" style={{ left: (width - 300) / 2, top: TOPH + 40 }}>
        <div className="dtitle">{rg.t("Sorin putka", "Sori jail", "Cárcel de Sori")}</div>
        <img className="bigpuck" src={rg.asset("img/poliisi.png")} />
        <div className="dtext">{luckFailed ? msg : rg.t("Pääset pois sakolla, mustamakkaralla tai heittämällä 5 tai 6.", "Get out with a fine, a black sausage, or by rolling 5 or 6.", "Sal pagando una multa, con una morcilla o sacando 5 o 6.")}</div>
        {btns}
      </div>
    );
  }
  return null;
}

